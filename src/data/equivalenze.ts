/**
 * Tabella per le sostituzioni alimentari.
 *
 * FONTE PRINCIPALE: CREA — Tabelle di composizione degli alimenti, edizione 2019
 * (alimenti.crea.gov.it), che è il riferimento nazionale italiano. Dove CREA non
 * ha una voce si usa USDA FoodData Central o l'etichetta commerciale, e il campo
 * `nota` lo dichiara.
 *
 * Tre avvertenze che cambiano i numeri:
 *
 * 1. In CREA "carboidrati" significa carboidrati DISPONIBILI, cioè al netto
 *    della fibra. USDA invece usa "carbohydrate by difference", che la fibra la
 *    include. Per riso e pasta cambia poco; per legumi, semi di chia e patate
 *    dolci è un errore grosso. Tutti i valori qui sotto sono disponibili: dove
 *    la fonte era USDA il dato è già stato convertito.
 *
 * 2. CREA calcola le kcal come carb x 3.75 + proteine x 4 + grassi x 9 +
 *    fibra x 2, mentre le etichette UE usano carb x 4. Su un alimento molto
 *    amidaceo ballano ~5%. Le kcal qui sono quelle della fonte citata: non
 *    tornano al grammo con quelle stampate sulla confezione.
 *
 * 3. CREA 2019 ha rivisto al ribasso pasta e patate rispetto alle vecchie
 *    tabelle INRAN ancora in giro sul web (patate da 17.9 a 16.0 g di
 *    carboidrati). È il motivo per cui la regola classica "80 g di pasta = 300 g
 *    di patate" non regge: con i dati aggiornati servono circa 360 g. L'app
 *    calcola le porzioni dai macro, non dai rapporti tradizionali.
 */

