/**
 * foods.ts - Database alimenti dell'app gymbro.
 *
 * Tutti i valori nutrizionali sono SEMPRE per 100 g (o 100 ml per i liquidi).
 * `prezzoIndicativo` e' il prezzo indicativo in EUR della confezione tipica di vendita
 * (non del singolo 100 g) ed e' puramente orientativo: i prezzi cambiano spesso.
 *
 * ---------------------------------------------------------------------------
 * NOTA SUL FORMATO DEL LINK DI RICERCA EUROSPIN (verificato a settembre 2026)
 * ---------------------------------------------------------------------------
 * online.eurospin.com e' una single page application: l'HTML iniziale non contiene
 * il form di ricerca, quindi il formato e' stato dedotto da queste evidenze:
 *   1. https://online.eurospin.com/robots.txt contiene la riga `Disallow: *\/search`
 *      -> il percorso della ricerca e' `/search` (nessuna regola menziona "ricerca").
 *   2. https://online.eurospin.com/ricerca?q=proteine risponde HTTP 404
 *      -> il percorso italiano `/ricerca` NON e' quello corretto.
 *   3. https://online.eurospin.com/search?q=proteine risponde 200 (shell della SPA).
 * Il percorso `/search` e' quindi confermato; il nome del parametro `q` e' quello
 * convenzionale ma NON e' verificabile lato server (la SPA popola i risultati in JS).
 * Se dovesse cambiare, basta aggiornare EUROSPIN_SEARCH_BASE / eurospinSearch():
 * tutti i campi `ricercaUrl` seguono esattamente lo stesso schema.
 *
 * Sui marchi: `marca` e' valorizzato solo dove il marchio Eurospin e' ragionevolmente
 * noto; altrove il prodotto e' indicato con un nome generico (nessun marchio inventato).
 */

export type FoodCategory =
  | 'proteine-polvere' | 'snack-proteico' | 'latticini' | 'carne' | 'pesce'
  | 'uova' | 'verdura' | 'frutta' | 'cereali' | 'legumi' | 'grassi'
  | 'integratori' | 'bevande' | 'dispensa';

/** Valori nutrizionali sempre per 100 g (o 100 ml per i liquidi). */
export interface Food {
  id: string;                 // kebab-case unico
  nome: string;
  marca?: string;             // marchio Eurospin se noto (es. 'Vitalley', 'Land', 'Fior di Natura')
  categoria: FoodCategory;
  kcal: number;
  proteine: number;
  carbs: number;
  grassi: number;
  fibre?: number;
  porzioneTipica: number;     // g/ml/pz di una porzione tipica
  unita: 'g' | 'ml' | 'pz';
  prezzoIndicativo?: number;  // EUR, indicativo
  eurospin: boolean;          // true se reperibile da Eurospin
  ricercaUrl?: string;        // link di ricerca su online.eurospin.com (solo se eurospin === true)
  tagFase?: ('definizione' | 'forza' | 'massa' | 'mantenimento')[];
  note?: string;
}

/** Base url della ricerca prodotti su online.eurospin.com (vedi nota in testa al file). */
export const EUROSPIN_SEARCH_BASE = 'https://online.eurospin.com/search';

/** Costruisce il link di ricerca Eurospin per un termine qualsiasi (termine urlencoded). */
export function eurospinSearch(term: string): string {
  return `${EUROSPIN_SEARCH_BASE}?q=${encodeURIComponent(term)}`;
}

