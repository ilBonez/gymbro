/** Ritorna un alimento dal suo id. */
export function getFood(id: string): Food | undefined {
  return FOODS.find((f) => f.id === id);
}

/** Filtra gli alimenti per categoria. */
export function foodsByCategory(categoria: FoodCategory): Food[] {
  return FOODS.filter((f) => f.categoria === categoria);
}

/** Solo gli alimenti reperibili da Eurospin (per la lista della spesa). */
export function foodsEurospin(): Food[] {
  return FOODS.filter((f) => f.eurospin);
}
