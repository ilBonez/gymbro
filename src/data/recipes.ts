/** Numero totale di ricette in archivio. */
export const RECIPES_COUNT = RECIPES.length;

/** Ricette filtrate per momento della giornata. */
export function recipesByMeal(momento: Meal): Recipe[] {
  return RECIPES.filter((r) => r.momenti.includes(momento));
}

/** Ricette compatibili con una fase di allenamento. */
export function recipesByFase(fase: Recipe['fasi'][number]): Recipe[] {
  return RECIPES.filter((r) => r.fasi.includes(fase));
}

/** Tutti gli id degli alimenti usati nelle ricette (utile per test di integrita con FOODS). */
export function recipeFoodIds(): string[] {
  const ids = new Set<string>();
  for (const r of RECIPES) {
    for (const i of r.ingredienti) {
      if (i.foodId) ids.add(i.foodId);
    }
  }
  return [...ids];
}

/** Type guard di comodo: verifica che un Food sia utilizzabile in una ricetta. */
export function isUsableFood(f: Food | undefined): f is Food {
  return !!f;
}
